/** Agent模型绑定区域的集中双语文案；避免组件内散落状态说明。 */
export function modelBindingText(key: keyof typeof zh, values: Record<string, string> = {}): string {
  let text: string = (modelSettingsLocale.value === "en" ? en : zh)[key];
  for (const [name, value] of Object.entries(values)) text = text.replace(`{${name}}`, value);
  return text;
}

